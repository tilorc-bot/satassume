"""Compile the families of rows into ``templates/_compiled_rows.py`` (#249).

    python tools/compile_rows.py           # write the file
    python tools/compile_rows.py --check   # exit 1 if it is out of date

The family modules (``templates/trig.py`` ...) state rows as SymPy
booleans, the source to read and edit.  Building those booleans costs tens
of milliseconds per family, and the rules they compile to are plain data,
so the templates are registered from this compiled form
(``wiring.load``) and the family modules are not imported when a query is
answered.  ``tests/test_compiled_rows.py`` fails when the file is out of
date.
"""
import importlib
import os
import pprint
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "satassume", "knowledge", "templates", "_compiled_rows.py")

HEADER = '''"""The families of rows, compiled (#249): generated by
``tools/compile_rows.py`` from the ``RULES`` of the family modules.  Do not
edit; edit the family module and run ``python tools/compile_rows.py``.

``FAMILIES``: ``(family, ((function name, arity, terms, rules), ...))``:
the number of arguments (or the tuple of the numbers), and for each
number ``n`` its terms ``(n, ((argument, c), ...))`` (``c`` an int or the
text of an exact real number; also ``('inner', i)``, ``('times', i, k)``
and ``('of_constant', i, text)``) and its rules ``(n, ((premises,
conclusion), ...))`` of literals ``(slot, predicate, sign)``, a rule of a
row whose node has a shape with the shape as a third element
(``_rows.compile_rows``).
"""
'''


def stand_ins(row_families) -> None:
    """Give each function a family declares by name and this SymPy lacks
    (``owens_t`` before SymPy 1.15) a stand-in class of that name in its
    module, before the family modules are imported: the rows about it then
    compile as with the SymPy that has it, and the file is the same on
    every SymPy (``wiring.load`` skips the function where it is missing).
    Only this process sees the stand-ins."""
    from sympy import Function
    for _, declared in row_families:
        for fn in declared:
            if isinstance(fn, str):
                module, _, name = fn.partition(":")
                m = importlib.import_module(module)
                if not hasattr(m, name):
                    setattr(m, name, type(name, (Function,), {"__module__": module}))


def source() -> str:
    """The text of ``_compiled_rows.py`` for the current rows."""
    from satassume.knowledge.templates import ROW_FAMILIES
    from satassume.knowledge.templates._rows import by_function, compile_rows
    stand_ins(ROW_FAMILIES)
    families = []
    for family, _ in ROW_FAMILIES:
        module = importlib.import_module(f"satassume.knowledge.templates.{family}")
        families.append((family, tuple((fn.__name__, *compile_rows(fn, rows))
                                       for fn, rows in by_function(module.RULES))))
    return HEADER + "\nFAMILIES = " + pprint.pformat(tuple(families), width=99) + "\n"


def main(argv):
    text = source()
    current = ""
    if os.path.exists(OUT):
        with open(OUT) as f:
            current = f.read()
    if "--check" in argv:
        if current != text:
            print(f"{OUT} is out of date: run python tools/compile_rows.py")
            return 1
        return 0
    if current != text:
        with open(OUT, "w") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.path.insert(0, ROOT)
    sys.exit(main(sys.argv[1:]))
