"""gen_rule_tables.py [--check]: writes the engine's rule block tables for Rust (S2, issue 323).

Offline, and not ported: Tilo, 7 Nov, "None of the offline stuff should be ported". The engine's block is rules.py's
RULE_INTERNAL over NPRED variables, a pure function of the static RULES (engine.py:317, ref.py:218 and session_glue.rs
pass nothing else, and registration never changes it). This script asks satassume/sat/solver.py's `_rule_tables`, the
pure-Python path's own builder, for that block's checked clauses and model table, and writes them as Rust constants to
solver_rs/src/rule_tables_gen.rs. Rust's `set_rule_block` uses them only when the block it is given has exactly these
clauses and this nvars; any other block is checked and enumerated in Rust (block.rs), so a stale file costs a rebuild
of the models, never a wrong table. `--check` regenerates and compares byte for byte (test_rule_tables.py runs it).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "solver_rs", "src", "rule_tables_gen.rs")


def tables():
    """`(clauses, n, models)` as `_rule_tables` computes them for the engine's block."""
    from satassume.knowledge.rules import NPRED, RULE_INTERNAL
    from satassume.sat.solver import _rule_tables
    (clauses, closure), n = _rule_tables(RULE_INTERNAL, NPRED)
    return clauses, n, closure.models


def render() -> str:
    clauses, n, models = tables()
    width = (2 * n + 3) // 4
    out = [
        "// @generated by rust-spike/slice/gen_rule_tables.py: don't edit, rerun it (test_rule_tables.py checks the file).",
        "//! The engine's rule block, rules.py's RULE_INTERNAL over NPRED variables, as satassume/sat/solver.py's",
        "//! `_rule_tables` checks it and enumerates its models. Offline data, not ported (S2, issue 323).",
        "",
        f"pub const NVARS: usize = {n};",
        "",
        f"pub const CLAUSES: [&[u32]; {len(clauses)}] = [",
    ]
    out += [f"    &[{', '.join(str(l) for l in c)}]," for c in clauses]
    out += ["];", "", f"/// Each model as a mask over the {2 * n} relative literals (bit 2*i: variable i true; 2*i + 1: false), ascending.",
            f"pub const MODELS: [u128; {len(models)}] = ["]
    out += [f"    0x{m:0{width}x}," for m in models]
    out += ["];", ""]
    return "\n".join(out)


def main(argv):
    check = "--check" in argv
    text = render()
    if check:
        with open(OUT) as fh:
            old = fh.read()
        if old != text:
            print(f"{OUT} is stale: rerun gen_rule_tables.py", file=sys.stderr)
            return 1
        print("rule_tables_gen.rs matches _rule_tables")
        return 0
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, ROOT)
    sys.exit(main(sys.argv[1:]))
